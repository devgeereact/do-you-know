 ADD COLUMN curriculum_tags JSON NULL,
 ADD COLUMN is_ranked BOOLEAN NOT NULL DEFAULT TRUE,
 ADD COLUMN publish_at DATETIME(6) NULL,
 ADD COLUMN seo_title VARCHAR(255) NULL,
 ADD COLUMN seo_description TEXT NULL,
 ADD COLUMN created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 ADD CONSTRAINT quiz_age_bounds CHECK (age_min IS NULL OR (age_min BETWEEN 0 AND 120)),
 ADD CONSTRAINT quiz_age_order CHECK (age_max IS NULL OR (age_max BETWEEN 0 AND 120 AND (age_min IS NULL OR age_max >= age_min)));

CREATE TABLE curriculum_tags (
 code VARCHAR(100) PRIMARY KEY,
 label VARCHAR(160) NOT NULL,
 system VARCHAR(100) NOT NULL,
 age_min INT NULL,
 age_max INT NULL,
 sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE blocked_words (
 word VARCHAR(100) PRIMARY KEY,
 CONSTRAINT blocked_word_format CHECK (word REGEXP '^[a-z0-9]+$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE app_settings (
 id CHAR(36) PRIMARY KEY,
 user_id CHAR(36) NOT NULL UNIQUE,
 theme VARCHAR(8) NOT NULL DEFAULT 'light',
 notifications_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY (user_id) REFERENCES profiles(id) ON DELETE CASCADE,
 CONSTRAINT setting_theme CHECK (theme IN ('light','dark'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
